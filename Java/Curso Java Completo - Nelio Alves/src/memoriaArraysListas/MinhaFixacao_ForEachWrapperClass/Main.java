package memoriaArraysListas.MinhaFixacao_ForEachWrapperClass;

public class Main {
    static void main(String[] args) {

        Integer[] numerosInteiros = new Integer[7];

        numerosInteiros[0] = 1;
        numerosInteiros[1] = 2;
        numerosInteiros[2] = 3;

        for (Integer numero : numerosInteiros) {

            System.out.println(numero);

        }

    }

}
