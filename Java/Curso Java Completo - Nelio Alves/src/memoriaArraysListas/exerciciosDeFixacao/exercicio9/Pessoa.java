package memoriaArraysListas.exerciciosDeFixacao.exercicio9;

public final class Pessoa {
    private final String name;
    private final int age;

    public Pessoa(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {

        return name;

    }

    public int getAge() {

        return age;

    }

}
